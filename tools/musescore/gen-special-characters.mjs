#!/usr/bin/env node
// Generates the text editor's special characters (roadmap E17) from MuseScore 4.7's own: the Common tab's lists in
// palette/widgets/specialcharactersdialog.cpp (Unicode accidentals, score symbols, text symbols), its Unicode ranges,
// and the Musical symbols tab's SMuFL categories (fonts/smufl/ranges.json), limited to symbols the engine knows by
// name (engraving/types/symnames.cpp), since a text writes a symbol as <sym>name</sym>. SMuFL code points come from
// fonts/smufl/glyphnames.json, so the editor can draw a symbol in a music font.
//
//   node tools/musescore/gen-special-characters.mjs [<ms47 root>]
//
// Writes components/score-editor/rich-text/special-characters.generated.json and smufl-codes.generated.json.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const ms = path.resolve(process.argv[2] ?? path.join(root, '../ms47-spike'));
const dialog = fs.readFileSync(path.join(ms, 'src/palette/widgets/specialcharactersdialog.cpp'), 'utf8').replace(/\/\/.*$/gm, '');
const symnames = fs.readFileSync(path.join(ms, 'src/engraving/types/symnames.cpp'), 'utf8');
const glyphnames = JSON.parse(fs.readFileSync(path.join(ms, 'fonts/smufl/glyphnames.json'), 'utf8'));
const ranges = JSON.parse(fs.readFileSync(path.join(ms, 'fonts/smufl/ranges.json'), 'utf8'));

const block = (name) => {
  const m = dialog.match(new RegExp(`${name}\\[\\]\\s*=\\s*\\{([\\s\\S]*?)\\};`));
  if (!m) throw new Error(`${name} not found`);
  return m[1];
};
const codes = (name) => [...block(name).matchAll(/0x([0-9a-fA-F]+)/g)].map((m) => parseInt(m[1], 16));
const syms = (name) => [...block(name).matchAll(/SymId::(\w+)/g)].map((m) => m[1]);

// The engine's symbol names, in SymId order.
const namesBlock = symnames.slice(symnames.indexOf('s_symNames {'));
const known = new Set([...namesBlock.slice(0, namesBlock.indexOf('} };')).matchAll(/"([^"]+)"/g)].map((m) => m[1]));
const codeOf = (name) => {
  const cp = glyphnames[name]?.codepoint;
  return cp ? parseInt(cp.replace(/^U\+/, ''), 16) : null;
};

const smuflCodes = {};
for (const name of known) {
  const code = codeOf(name);
  if (code !== null) smuflCodes[name] = code;
}

const common = [
  ...codes('unicodeAccidentals').map((c) => ({ c })),
  ...syms('commonScoreSymbols').map((s) => ({ s })),
  ...codes('commonTextSymbols').map((c) => ({ c })),
];
const smufl = Object.values(ranges)
  .map((range) => ({ label: range.description, glyphs: range.glyphs.filter((g) => known.has(g) && g in smuflCodes) }))
  .filter((range) => range.glyphs.length);
const unicode = [...block('unicodeRanges').matchAll(/\{\s*0x([0-9a-fA-F]+),\s*0x([0-9a-fA-F]+),\s*QT_TRANSLATE_NOOP\("[^"]*",\s*"([^"]+)"\)\s*\}/g)].map(
  (m) => ({ label: m[3], first: parseInt(m[1], 16), last: parseInt(m[2], 16) }),
);

const out = path.join(root, 'components/score-editor/rich-text');
const comment = 'Generated by tools/musescore/gen-special-characters.mjs from MuseScore 4.7 (specialcharactersdialog.cpp, symnames.cpp, fonts/smufl). Do not edit; regenerate.';
fs.writeFileSync(
  path.join(out, 'special-characters.generated.json'),
  `{"_comment": ${JSON.stringify(comment)},\n "common": ${JSON.stringify(common)},\n "smufl": [\n${smufl.map((r) => `  ${JSON.stringify(r)}`).join(',\n')}\n ],\n "unicode": [\n${unicode.map((r) => `  ${JSON.stringify(r)}`).join(',\n')}\n ]}\n`,
);
fs.writeFileSync(path.join(out, 'smufl-codes.generated.json'), `${JSON.stringify({ _comment: comment, codes: smuflCodes })}\n`);
console.log(`common ${common.length}, SMuFL ${smufl.length} categories / ${smufl.reduce((n, r) => n + r.glyphs.length, 0)} symbols, unicode ${unicode.length} ranges, codes ${Object.keys(smuflCodes).length}`);
