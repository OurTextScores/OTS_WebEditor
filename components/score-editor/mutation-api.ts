export const hasMutationApi = (score: Score | null): score is Score & MutationMethods => {
  if (!score) {
    return false;
  }

  const candidate = score as unknown as Record<string, unknown>;
  return Boolean(
    candidate.deleteSelection ||
    candidate.undo ||
    candidate.redo ||
    candidate.pitchUp ||
    candidate.pitchDown ||
    candidate.doubleDuration ||
    candidate.halfDuration,
  );
};
